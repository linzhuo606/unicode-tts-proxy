package com.ttsproxy.core

/**
 * 下游引擎本来就处理得好的标点：**原样交给它，内置词典不许替换。**
 *
 * 这是本项目的范围原则在标点上的落地——**只管下游读不出来的字符，别的一概不碰**。
 * 标点对下游来说多半不是「要念出来的符号」，而是韵律指令：句号、逗号、顿号告诉它
 * 在哪里停、停多久；引号告诉它语气。中文引擎对这些处理得很好，我们插手只会更糟。
 *
 * ## 两类，都吃过亏
 *
 * **断句标点**。有一版给「CJK 符号和标点」整块补了读法，`。` 被读成「句号」两个字、
 * `、` 读成「顿号」，长文朗读当场挤成一团：下游看不到断句，句与句之间不再停顿；
 * [Chunker] 也靠句号断句，一段长文成了一整块，音频撑爆缓冲、开始丢数据——
 * 症状和更早一次缓冲丢数据的故障一模一样。
 *
 * **引号**。曾经统一读成一个字「引」，理由是弯引号被读成「左双引号」太啰嗦。
 * 后来定下的规矩是连「引」也不读：弯引号交给下游多半是安静的，比我们插一个字更干净。
 * 代价是 ASCII 的 `"` `'` 会被下游按它自己的规矩念出来——这一条是用户明确接受的取舍。
 *
 * ## 两道闸
 *
 * 词典生成时收了这些标点直接报错（tools 侧 GenerateDict 里有同一份清单），
 * 运行时就算词典里有，内置条目也一律忽略。
 *
 * **用户自定义词典不受限制**：那是用户自己的明确选择，想让某个标点读什么就读什么。
 *
 * **破折号、省略号、间隔号、连接号**也在清单里。它们和句号、顿号同属国家标准《标点符号用法》，
 * 早先被有意读成「破折号」「省略号」「间隔号」，后来用户定了交还下游——
 * 「艾萨克·牛顿」不该读成「艾萨克 间隔号 牛顿」，「他沉默了……」也不该读出「省略号」。
 */
object NativePunctuation {

    fun isProtected(cp: Int): Boolean = when (cp) {
        // ASCII 断句标点、括号与引号
        0x21, 0x2C, 0x2E, 0x3A, 0x3B, 0x3F -> true
        0x28, 0x29, 0x5B, 0x5D, 0x7B, 0x7D -> true
        0x22, 0x27 -> true
        // 西文引号：双尖角与单尖角
        0x00AB, 0x00BB, 0x2039, 0x203A -> true
        // 通用标点里的成对引号（含下九、反九那几个变体）
        in 0x2018..0x201F -> true
        0x2E42 -> true
        // 中文标点里的间隔号（含台港常拿来当间隔号用的连字点）、连接号、破折号、横线、两点、省略号
        0x00B7, 0x2027 -> true
        0x2010, 0x2013, 0x2014, 0x2015 -> true
        0x2025, 0x2026 -> true
        // 全角：中文正文里最常见的那一套
        0xFF01, 0xFF0C, 0xFF0E, 0xFF1A, 0xFF1B, 0xFF1F -> true
        0xFF02, 0xFF07 -> true
        0xFF08, 0xFF09, 0xFF3B, 0xFF3D, 0xFF5B, 0xFF5D -> true
        0xFF5E, 0xFF5F, 0xFF60 -> true
        0xFF61, 0xFF62, 0xFF63, 0xFF64 -> true
        // CJK：顿号、句号；书名号、直角引号、方头括号；六角括号一族、波浪号与竖排引号
        0x3001, 0x3002 -> true
        in 0x3008..0x3011 -> true
        in 0x3014..0x301F -> true
        else -> false
    }

    /** 这条内置条目是不是要被忽略。只拦单码位的内置条目，用户条目一律放行。 */
    internal fun shields(entry: SymbolDict.Entry): Boolean =
        !entry.fromUser && entry.key.size == 1 && isProtected(entry.key[0])
}
